#!/usr/bin/env node
/**
 * Writes docs-spec/SCREENSHOTS.md: every <Screenshot /> in docs/, grouped by docs page, with the
 * app route, what the screen must show, and whether it is captured. Run after adding or removing
 * a screenshot:
 *
 *   pnpm screenshots:list
 *
 * Shots whose key starts with a prefix in BLOCKED are marked with the reason.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const DOCS = path.join(ROOT, "docs");
const OUT = path.join(ROOT, "docs-spec/SCREENSHOTS.md");
const captured = new Set(JSON.parse(fs.readFileSync(path.join(ROOT, "src/data/screenshots.json"), "utf8")));

const BLOCKED = {
  "gateways/": "Needs the gateways work (PR 1623): `/onboarding/gateways` and the gateway detail page.",
};

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : /\.mdx$/.test(e.name) ? [p] : [];
  });

const byFile = new Map();
for (const file of walk(DOCS).sort()) {
  const src = fs.readFileSync(file, "utf8");
  for (const m of src.matchAll(/<Screenshot\b([\s\S]*?)\/>/g)) {
    const props = {};
    for (const p of m[1].matchAll(/(\w+)=(?:"([^"]*)"|\{"([^"]*)"\}|'([^']*)')/g)) props[p[1]] = p[2] ?? p[3] ?? p[4];
    if (!props.page || !props.id) continue;
    const rel = path.relative(ROOT, file);
    const line = src.slice(0, m.index).split("\n").length;
    const key = `${props.page}/${props.id}`;
    const blocked = Object.entries(BLOCKED).find(([prefix]) => key.startsWith(prefix))?.[1];
    if (!byFile.has(rel)) byFile.set(rel, []);
    byFile.get(rel).push({ ...props, key, line, blocked });
  }
}

const cell = (s = "") => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const all = [...byFile.values()].flat();
const done = all.filter((s) => captured.has(s.key)).length;
const blocked = all.filter((s) => s.blocked && !captured.has(s.key)).length;
const doneDe = all.filter((s) => captured.has(`de:${s.key}`)).length;

let md = `# Screenshots

Generated by \`pnpm screenshots:list\` from the \`<Screenshot />\` elements in docs/. Don't edit by hand.

${all.length} screenshots on ${byFile.size} pages: ${done} captured in English, ${all.length - done} to do${blocked ? ` (${blocked} blocked)` : ""}; ${doneDe} captured in German.
German pages show the English picture until the German one is captured (\`node scripts/screenshots/capture.mjs --lang de\`).
Each is captured in light and dark at 1440×900 @2x into \`static/img/screens/<page>/<id>.<lang>.<theme>.png\` by
\`pnpm screenshots\` (see \`scripts/screenshots/capture.mjs\`; record ids and click steps go in \`scripts/screenshots/shots.json\`).
Until then the page shows a placeholder with the route and the state below.
`;

for (const [file, shots] of byFile) {
  md += `\n## ${file}\n\n| EN | DE | Id | Route | What the screen shows |\n|---|---|---|---|---|\n`;
  for (const s of shots) {
    const mark = captured.has(s.key) ? "✅" : s.blocked ? "⏸" : "⬜";
    const what = [s.state || s.alt, s.blocked ? `**Blocked:** ${s.blocked}` : ""].filter(Boolean).join("<br>");
    const de = captured.has(`de:${s.key}`) ? "✅" : "⬜";
    md += `| ${mark} | ${de} | [\`${s.id}\`](../${file}#L${s.line}) | \`${cell(s.route)}\` | ${cell(what)} |\n`;
  }
}

fs.writeFileSync(OUT, md);
console.log(`Wrote ${path.relative(ROOT, OUT)}: ${all.length} screenshots on ${byFile.size} pages.`);
